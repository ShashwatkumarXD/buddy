"""A tiny hand-drawn pixel font for buddy's speech bubbles: mixed case, proportional, 9 rows per line.

Rows 0-6 hold capitals (row 6 is the baseline), lowercase sits in rows 2-6, and descenders use rows 7-8.
"#" is ink; a glyph listed in COLORED is painted in its own colour instead (the heart is red).
"""
from PIL import Image

HEIGHT = 9  # rows per line of text
LEADING = 2  # blank rows between lines
SPACING = 1  # blank columns between letters
SPACE = 3  # width of " "
COLORED = {"♥": (232, 64, 96, 255)}


def _glyph(*rows: str) -> list[str]:
    """Pad a glyph to HEIGHT rows (the unlisted bottom rows are blank)."""
    width = len(rows[0])
    return list(rows) + ["." * width] * (HEIGHT - len(rows))


