GLYPHS = {ch: _glyph(*rows) for table in (_UPPER, _LOWER, _DIGITS, _MARKS) for ch, rows in table.items()}


def supports(text: str) -> bool:
    return all(ch == " " or ch in GLYPHS for ch in text)


def _width(ch: str) -> int:
    return SPACE if ch == " " else len(GLYPHS[ch][0])


def line_width(line: str) -> int:
    return sum(_width(ch) for ch in line) + SPACING * max(len(line) - 1, 0)


def wrap(text: str, max_width: int) -> list[str]:
    """Break text into lines no wider than max_width pixels (a single over-long word gets a line of its own)."""
    lines: list[str] = []
    for word in text.split():
        if lines and line_width(lines[-1] + " " + word) <= max_width:
            lines[-1] += " " + word
        else:
            lines.append(word)
    return lines


def block_size(lines: list[str]) -> tuple[int, int]:
    return max((line_width(line) for line in lines), default=0), len(lines) * HEIGHT + LEADING * max(len(lines) - 1, 0)


def draw(im: Image.Image, lines: list[str], x: int, y: int, ink: tuple, limit: int | None = None, center: bool = True) -> None:
    """Draw the lines with their top-left at (x, y); only the first `limit` characters (typewriter effect)."""
    block_w, _ = block_size(lines)
    shown = 0
    for row, line in enumerate(lines):
        cx = x + ((block_w - line_width(line)) // 2 if center else 0)
        cy = y + row * (HEIGHT + LEADING)
        for ch in line:
            if limit is not None and shown >= limit:
                return
            shown += 1
            if ch != " ":
                paint = COLORED.get(ch, ink)
                for j, glyph_row in enumerate(GLYPHS[ch]):
                    for i, c in enumerate(glyph_row):
                        if c == "#":
                            im.putpixel((cx + i, cy + j), paint)
            cx += _width(ch) + SPACING
